-- Bank Transfer payment method: tickets are never issued instantly — the
-- payment sits "on_hold" until an admin verifies the deposit in the FBC
-- account and approves/rejects/stalls it from the payments dashboard.

-- Tickets minted off an approved bank transfer need a matching enum value,
-- otherwise the fulfillment insert into tickets.payment_method fails.
ALTER TYPE public.payment_method_type ADD VALUE IF NOT EXISTS 'bank_transfer';

-- Review bookkeeping lives on the payment row (status stays 'on_hold' while
-- it's awaiting a decision or more information from the buyer).
ALTER TABLE public.payments
  ADD COLUMN IF NOT EXISTS review_status text,
  ADD COLUMN IF NOT EXISTS review_reason text,
  ADD COLUMN IF NOT EXISTS reviewed_at timestamptz,
  ADD COLUMN IF NOT EXISTS reviewed_by uuid REFERENCES public.profiles(id);

-- Same admin on/off switch Stripe, Paynow and EcoCash already have.
ALTER TABLE public.platform_config ADD COLUMN IF NOT EXISTS bank_transfer_enabled boolean NOT NULL DEFAULT true;

-- Proof-of-payment files (bank slips, screenshots, PDFs). PRIVATE bucket —
-- contents are financial documents, so no public read policy is created;
-- admins view proofs through short-lived signed URLs generated by
-- /api/admin/payments/[reference]/proof.
INSERT INTO storage.buckets (id, name, public, file_size_limit)
VALUES ('payment-proofs', 'payment-proofs', false, 20971520)
ON CONFLICT (id) DO UPDATE SET
  public = false,
  file_size_limit = 20971520;
